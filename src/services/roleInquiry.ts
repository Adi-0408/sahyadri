/**
 * Checks if an email is system-generated (e.g. mobile@propertyvishva.com, mobile@sahyadriland.com, etc.)
 * Returns true if the email is dummy, auto-generated, or empty.
 */
export const isAutoGeneratedEmail = (emailStr?: string | null): boolean => {
  if (!emailStr) return true;
  const clean = String(emailStr).trim().toLowerCase();
  if (!clean || !clean.includes('@')) return true;
  const [local, domain] = clean.split('@');
  if (!local || !domain) return true;

  // If local part is just a phone number (e.g. 10 digits)
  if (/^\d{8,15}$/.test(local)) {
    return true;
  }

  // If local part is an auto-generated user identifier pattern
  if (/^(user|guest|buyer|seller|agent|test|client|member)[-_]?\d*/i.test(local)) {
    return true;
  }

  const dummyDomains = [
    'propertyvishva.com',
    'sahayadrilanddev.com',
    'sahyadriland.com',
    'sahyadri.com',
    'astitvarealestate.com',
    'propertyastitv.com'
  ];

  if (dummyDomains.includes(domain)) {
    return true;
  }

  return false;
};

