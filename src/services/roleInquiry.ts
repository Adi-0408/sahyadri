/**
 * Admin permanently deletes a role inquiry and removes all mirrored records from all collections
 */
export const deleteRoleInquiry = async (
  inquiryId: string,
  item?: Partial<RoleInquiry>
): Promise<boolean> => {
  if (!inquiryId) return false;

  const collections = [
    'role_inquiries',
    'enquiries',
    'role_applications',
    'material_suppliers',
    'sellers',
    'buyers',
    'builders',
    'agents',
    'suppliers',
    'representatives'
  ];

  const deletePromises: Promise<any>[] = [];

  // 1. Delete direct document by inquiryId across relevant collections
  collections.forEach((col) => {
    deletePromises.push(deleteDocument(col, inquiryId).catch(() => {}));
  });

  // 2. If item has sourceCollection, delete there as well
  if (item?.sourceCollection && !collections.includes(item.sourceCollection)) {
    deletePromises.push(deleteDocument(item.sourceCollection, inquiryId).catch(() => {}));
  }

  // 3. If item has userId and it differs from inquiryId, delete that too
  if (item?.userId && item.userId !== inquiryId) {
    collections.forEach((col) => {
      deletePromises.push(deleteDocument(col, item.userId!).catch(() => {}));
    });
  }

  // 4. If item has mobile, check role-based document IDs (e.g. seller_8767261213, buyer_8080808080)
  const rawMob = item?.userMobile || (item as any)?.phone || (item as any)?.mobile;
  const mob = String(rawMob || '').replace(/[^0-9]/g, '').slice(-10);
  if (mob) {
    if (item?.requestedRole) {
      deletePromises.push(deleteDocument('role_applications', `${item.requestedRole}_${mob}`).catch(() => {}));
      deletePromises.push(deleteDocument('role_applications', `app_${item.requestedRole}_${mob}`).catch(() => {}));
    }
    if (item?.requestedRole === 'seller') {
      deletePromises.push(deleteDocument('sellers', `seller_${mob}`).catch(() => {}));
      deletePromises.push(deleteDocument('sellers', `app_seller_${mob}`).catch(() => {}));
    } else if (item?.requestedRole === 'buyer') {
      deletePromises.push(deleteDocument('buyers', `buyer_${mob}`).catch(() => {}));
    } else if (item?.requestedRole === 'builder') {
      deletePromises.push(deleteDocument('builders', `builder_${mob}`).catch(() => {}));
    } else if (item?.requestedRole === 'agent') {
      deletePromises.push(deleteDocument('agents', `agent_${mob}`).catch(() => {}));
    } else if (item?.requestedRole === 'supplier') {
      deletePromises.push(deleteDocument('suppliers', `supplier_${mob}`).catch(() => {}));
      deletePromises.push(deleteDocument('suppliers', `app_supplier_${mob}`).catch(() => {}));
      deletePromises.push(deleteDocument('material_suppliers', `supplier_${mob}`).catch(() => {}));
    }
  }

  await Promise.all(deletePromises);

  // 5. Clean local storage cache
  if (typeof window !== 'undefined') {
    try {
      const raw = localStorage.getItem('sahyadri_local_role_inquiries');
      if (raw) {
        const parsed = JSON.parse(raw);
        if (Array.isArray(parsed)) {
          const filtered = parsed.filter(
            (i: any) =>
              i &&
              i.id !== inquiryId &&
              i.userId !== inquiryId &&
              (!mob || String(i.userMobile || i.phone || '').replace(/[^0-9]/g, '').slice(-10) !== mob)
          );
          localStorage.setItem('sahyadri_local_role_inquiries', JSON.stringify(filtered));
        }
      }
    } catch {}
    window.dispatchEvent(new CustomEvent('role_inquiry_updated'));
  }

  return true;
};

