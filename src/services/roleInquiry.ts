export interface CleanAndDeduplicateResult {
  cleanedUsers: any[];
  mergedCount: number;
  purgedCount: number;
}

/**
 * Deduplicates users in 'users' collection and permanently purges orphaned ghost records:
 * 1. Purges ghost documents with empty names and no valid mobile (e.g. app_seller_..., builder_...)
 * 2. Merges duplicate documents sharing the same mobile number (e.g. phone-number doc ID vs Auth UID)
 * 3. Elevated role is preserved (highest privilege role wins)
 * 4. Deletes redundant duplicate documents from Firestore
 */
export const cleanAndDeduplicateUsers = async (rawUsers?: any[]): Promise<CleanAndDeduplicateResult> => {
  let list = Array.isArray(rawUsers) ? [...rawUsers] : [];
  if (list.length === 0) {
    try {
      list = await fetchCollection('users');
    } catch {
      list = [];
    }
  }

  let mergedCount = 0;
  let purgedCount = 0;

  // 1. Purge definite ghost records
  const validCandidates: any[] = [];
  for (const u of list) {
    if (!u) continue;
    const uId = String(u.id || u.uid || '').trim();
    const rawMob = String(u.mobile || u.phoneNumber || u.phone || '').replace(/[^0-9]/g, '');
    const cleanMob = rawMob.length >= 10 ? rawMob.slice(-10) : '';
    const name = String(u.name || u.fullName || '').trim();
    const email = String(u.email || '').trim().toLowerCase();

    const isGhostPrefix = uId.startsWith('app_seller_') || uId.startsWith('builder_') || uId.startsWith('seller_') || uId.startsWith('buyer_') || uId.startsWith('agent_');
    const hasRealName = name && !isGenericOrDummyName(name);
    const hasValidMob = cleanMob.length === 10;
    const hasValidEmail = email.includes('@') && !isAutoGeneratedEmail(email);

    // Ghost prefix with no legitimate name or phone -> purge!
    if (isGhostPrefix && (!hasRealName || !hasValidMob)) {
      try {
        await deleteDocument('users', uId);
        purgedCount++;
        console.log(`[Deduplicate] Purged ghost user doc: ${uId}`);
      } catch {}
      continue;
    }

    // No name, no valid email, no valid mobile -> purge!
    if (!hasRealName && !hasValidMob && !hasValidEmail) {
      try {
        await deleteDocument('users', uId);
        purgedCount++;
        console.log(`[Deduplicate] Purged empty user doc: ${uId}`);
      } catch {}
      continue;
    }

    validCandidates.push(u);
  }

  // 2. Group by 10-digit mobile number
  const groupedByMobile = new Map<string, any[]>();
  const nonMobileUsers: any[] = [];

  for (const u of validCandidates) {
    const rawMob = String(u.mobile || u.phoneNumber || u.phone || u.id || '').replace(/[^0-9]/g, '');
    const cleanMob = rawMob.length >= 10 ? rawMob.slice(-10) : '';
    if (cleanMob.length === 10) {
      if (!groupedByMobile.has(cleanMob)) {
        groupedByMobile.set(cleanMob, []);
      }
      groupedByMobile.get(cleanMob)!.push(u);
    } else {
      nonMobileUsers.push(u);
    }
  }

  const finalUsers: any[] = [...nonMobileUsers];

  for (const [cleanMob, dups] of groupedByMobile.entries()) {
    if (dups.length === 1) {
      finalUsers.push(dups[0]);
      continue;
    }

    // Pick canonical document:
    // Prefer authentic Firebase Auth UID (long string >= 20 chars, not starting with app_/builder_)
    let canonical = dups.find((d) => d.id && d.id.length >= 20 && !d.id.startsWith('app_') && !d.id.startsWith('builder_') && !d.id.startsWith('seller_'));
    if (!canonical) {
      canonical = dups.find((d) => d.name && !isGenericOrDummyName(d.name)) || dups[0];
    }

    // Pick highest privilege role among duplicates
    let bestRole = canonical.role || 'user';
    let bestRank = ROLE_RANK[String(bestRole).toLowerCase()] || 1;
    for (const d of dups) {
      const r = String(d.role || 'user').toLowerCase();
      const rank = ROLE_RANK[r] || 1;
      if (rank > bestRank) {
        bestRank = rank;
        bestRole = r;
      }
    }

    const realName = dups.find((d) => d.name && !isGenericOrDummyName(d.name))?.name || canonical.name || 'User';
    const realEmail = dups.find((d) => d.email && d.email.includes('@') && !isAutoGeneratedEmail(d.email))?.email || canonical.email || `${cleanMob}@sahyadri.com`;
    const realInterest = dups.find((d) => d.interest || d.interests || d.propertyInterest)?.interest || canonical.interest;
    const userCode = dups.find((d) => d.userCode)?.userCode || canonical.userCode;

    const mergedData = {
      ...canonical,
      name: realName,
      mobile: cleanMob,
      phone: cleanMob,
      phoneNumber: cleanMob,
      email: realEmail,
      role: bestRole,
      interest: realInterest || canonical.interest,
      userCode: userCode || canonical.userCode,
      status: canonical.status || 'active'
    };

    // Update canonical record in Firestore
    try {
      await updateDocument('users', canonical.id, {
        name: realName,
        mobile: cleanMob,
        phone: cleanMob,
        phoneNumber: cleanMob,
        email: realEmail,
        role: bestRole,
        interest: realInterest || canonical.interest,
        userCode: userCode || canonical.userCode,
        status: canonical.status || 'active'
      });
    } catch (e) {
      console.warn(`Could not update canonical user ${canonical.id}:`, e);
    }

    // Delete redundant duplicate documents from Firestore
    for (const d of dups) {
      if (d.id !== canonical.id) {
        try {
          await deleteDocument('users', d.id);
          mergedCount++;
          console.log(`[Deduplicate] Deleted duplicate user doc ${d.id} merged into ${canonical.id}`);
        } catch (delErr) {
          console.warn(`Could not delete duplicate user ${d.id}:`, delErr);
        }
      }
    }

    finalUsers.push(mergedData);
  }

  return {
    cleanedUsers: finalUsers,
    mergedCount,
    purgedCount
  };
};

/**
 * Synthesizes a standardized, approved Property document from any registered user
 * who has been elevated to 'seller' or 'builder', ensuring their listings appear on the website.
 */
export const synthesizePropertyFromUser = (u: any): any => {
  if (!u) return null;

  const rawMob = String(u.mobile || u.phoneNumber || u.phone || u.id || '').replace(/[^0-9]/g, '');
  const cleanMob = rawMob.length >= 10 ? rawMob.slice(-10) : '';
  const name = u.name && !isGenericOrDummyName(u.name)
    ? u.name
    : (u.role === 'builder' ? 'Registered Builder' : 'Property Owner');
  const role = String(u.role || 'seller').toLowerCase();

  const isBuilder = role === 'builder';
  const cat = isBuilder ? 'House' : 'Land';
  const type = 'sale';
  const title = isBuilder
    ? `${name} Construction & Residential Project`
    : `Verified Property for Sale by ${name}`;
  const priceNum = isBuilder ? 1500000 : 500000;
  const targetPropId = `prop-user-${u.id || cleanMob || Date.now()}`;

  return {
    id: targetPropId,
    roleInquiryId: u.id || (cleanMob ? `user_${cleanMob}` : `user_${Date.now()}`),
    userId: u.id || u.uid || cleanMob || 'admin',
    ownerName: name,
    mobileNumber: cleanMob || u.mobile || '',
    ownerPhone: cleanMob || u.phone || '',
    phone: cleanMob || u.phone || '',
    cleanMobile: cleanMob,
    email: u.email && !isAutoGeneratedEmail(u.email) ? u.email : '',
    category: cat,
    type: type,
    status: 'approved',
    adminApproved: true,
    isActive: true,
    title: title,
    propertyName: title,
    description: isBuilder
      ? `Verified new construction and residential project by registered builder ${name} in Sangli.`
      : `Verified plot and property for sale by registered seller ${name} in Sangli.`,
    expectedPrice: priceNum,
    price: priceNum,
    monthlyRent: 0,
    isNegotiable: true,
    district: u.district || 'Sangli',
    taluka: u.taluka || 'Miraj',
    cityVillage: u.city || u.cityVillage || 'Sangli',
    location: `${u.city || u.cityVillage ? (u.city || u.cityVillage) + ', ' : ''}${u.taluka || 'Miraj'}, ${u.district || 'Sangli'}`,
    builtUpArea: isBuilder ? 1200 : 0,
    carpetArea: isBuilder ? 950 : 0,
    plotAreaSqFt: isBuilder ? 1500 : 2000,
    plotAreaGuntha: isBuilder ? 1.5 : 2,
    bedrooms: isBuilder ? 3 : 0,
    bathrooms: isBuilder ? 2 : 0,
    images: Array.isArray(u.images) && u.images.length > 0 ? u.images : [],
    showPrice: true,
    showAddress: true,
    showOwnerName: true,
    showOwnerContact: true,
    showImages: true,
    createdAt: u.createdAt || new Date().toISOString(),
    reviewedAt: new Date().toISOString(),
    reviewedBy: 'Admin (System Sync)',
    source: 'user_role_sync'
  };
};

/**
 * Auto-Reconciliation: Scans ALL approved role inquiries and seller/builder users across collections
 * and guarantees that EVERY accepted inquiry and user has a corresponding live, approved property document in 'properties'.
 * If a matching property is missing, it synthesizes and creates it in Firestore as APPROVED.
 * If an existing property was pending or inactive, it updates it to APPROVED and active.
 */
export const syncApprovedRoleInquiriesWithProperties = async (): Promise<number> => {
  let syncedCount = 0;
  try {
    const [roleInqs, enquiries, roleApps, matSuppliers, sellers, builders, rawUsers, properties, suppliers] = await Promise.all([
      fetchCollection('role_inquiries').catch(() => []),
      fetchCollection('enquiries').catch(() => []),
      fetchCollection('role_applications').catch(() => []),
      fetchCollection('material_suppliers').catch(() => []),
      fetchCollection('sellers').catch(() => []),
      fetchCollection('builders').catch(() => []),
      fetchCollection('users').catch(() => []),
      fetchCollection('properties').catch(() => []),
      fetchCollection('suppliers').catch(() => [])
    ]);

    // 1. Run database deduplication & ghost cleanup first
    const { cleanedUsers } = await cleanAndDeduplicateUsers(rawUsers);

    let localList: any[] = [];
    if (typeof window !== 'undefined') {
      try {
        const raw = localStorage.getItem('sahyadri_local_role_inquiries');
        if (raw) localList = JSON.parse(raw);
      } catch {}
    }

    const allInquiries = [
      ...(Array.isArray(roleInqs) ? roleInqs : []),
      ...(Array.isArray(enquiries) ? enquiries.filter(isRoleInquiryDocument) : []),
      ...(Array.isArray(roleApps) ? roleApps.map((a: any) => normalizeMobileRoleDoc(a, 'role_applications')).filter(Boolean) : []),
      ...(Array.isArray(matSuppliers) ? matSuppliers.map((m: any) => normalizeMobileRoleDoc(m, 'material_suppliers')).filter(Boolean) : []),
      ...(Array.isArray(sellers) ? sellers : []),
      ...(Array.isArray(builders) ? builders : []),
      ...(Array.isArray(suppliers) ? suppliers : []),
      ...(Array.isArray(localList) ? localList : [])
    ];

    // Filter for approved / accepted inquiries
    const approvedInquiries = allInquiries.filter((i: any) =>
      i &&
      (i.status === 'approved' || i.status === 'accepted')
    );

    // Track processed keys to avoid duplicates
    const processedInqIds = new Set<string>();

    // 2. Reconcile Approved Inquiries with Properties
    for (const inq of approvedInquiries) {
      const inqId = String(inq.id || inq.userId || '').trim();
      const inqKey = inqId || `${inq.userMobile}_${inq.requestedRole}`;
      if (processedInqIds.has(inqKey)) continue;
      processedInqIds.add(inqKey);

      // Check if this inquiry already has a property in 'properties'
      const existingProp = (properties || []).find((p: any) =>
        p &&
        (
          (inq.id && p.roleInquiryId === inq.id) ||
          (p.id === inq.id) ||
          (inq.id && p.id === `prop-inquiry-${inq.id}`) ||
          (inq.id && p.id === `prop-seller-${inq.id}`)
        )
      );

      if (existingProp && existingProp.id) {
        if (existingProp.status !== 'approved' || existingProp.adminApproved !== true || existingProp.isActive !== true) {
          try {
            await updateDocument('properties', existingProp.id, {
              status: 'approved',
              adminApproved: true,
              isActive: true,
              reviewedAt: new Date().toISOString(),
              reviewedBy: 'Admin (System Sync)'
            });
            syncedCount++;
            console.log(`[Auto-Sync] Activated existing property ${existingProp.id} for accepted inquiry ${inq.id}`);
          } catch (syncErr) {
            console.warn(`Could not sync property ${existingProp.id}:`, syncErr);
          }
        }
      } else {
        const newPropertyDoc = synthesizePropertyFromInquiry(inq);
        if (newPropertyDoc) {
          try {
            await createDocument('properties', newPropertyDoc);
            syncedCount++;
            properties.push(newPropertyDoc);
            console.log(`[Auto-Sync] Created missing approved property for inquiry ${inq.id}:`, newPropertyDoc.id);
          } catch (createErr) {
            console.warn(`Could not create property for accepted inquiry ${inq.id}:`, createErr);
          }
        }
      }
    }

    // 3. Reconcile Registered Users with 'seller' or 'builder' role:
    // Any user elevated to seller or builder MUST have an active property on the website!
    const sellerOrBuilderUsers = (Array.isArray(cleanedUsers) ? cleanedUsers : []).filter((u: any) =>
      u &&
      (u.role === 'seller' || u.role === 'builder') &&
      !u.isBlocked &&
      !u.isBlacklisted
    );

    for (const u of sellerOrBuilderUsers) {
      const uMob = String(u.mobile || u.phoneNumber || u.phone || u.id || '').replace(/[^0-9]/g, '').slice(-10);
      const uId = String(u.id || u.uid || '').trim();

      const hasProp = (properties || []).some((p: any) =>
        p &&
        (
          (uId && (p.userId === uId || p.roleInquiryId === uId || p.id === `prop-user-${uId}`)) ||
          (uMob && (
            p.cleanMobile === uMob ||
            (p.mobileNumber && String(p.mobileNumber).replace(/[^0-9]/g, '').slice(-10) === uMob) ||
            (p.ownerPhone && String(p.ownerPhone).replace(/[^0-9]/g, '').slice(-10) === uMob)
          ))
        )
      );

      if (!hasProp) {
        const userProp = synthesizePropertyFromUser(u);
        if (userProp) {
          try {
            await createDocument('properties', userProp);
            syncedCount++;
            properties.push(userProp);
            console.log(`[Auto-Sync] Created missing property for ${u.role} user ${u.name || uMob}:`, userProp.id);
          } catch (err) {
            console.warn(`Could not create property for user ${u.id}:`, err);
          }
        }
      }

      // Also ensure any pending inquiry matching this user is marked approved!
      for (const inq of allInquiries) {
        if (!inq || inq.status === 'approved' || inq.status === 'accepted') continue;
        const inqMob = String(inq.userMobile || inq.phone || inq.mobile || '').replace(/[^0-9]/g, '').slice(-10);
        const inqUserId = String(inq.userId || inq.uid || '').trim();
        const matchesUser = (uId && (inqUserId === uId || inq.id === uId)) ||
          (uMob && inqMob === uMob);

        if (matchesUser && inq.id) {
          try {
            const collectionToUpdate = (inq as any).sourceCollection || 'role_inquiries';
            await updateDocument(collectionToUpdate, inq.id, {
              status: 'approved',
              reviewedAt: new Date().toISOString(),
              reviewedBy: 'Admin (System Sync)'
            });
            inq.status = 'approved';
          } catch {}
        }
      }
    }

    if (syncedCount > 0 && typeof window !== 'undefined') {
      window.dispatchEvent(new Event('storage'));
      window.dispatchEvent(new CustomEvent('role_inquiry_updated', { detail: { syncedCount } }));
    }
  } catch (err) {
    console.warn('syncApprovedRoleInquiriesWithProperties error:', err);
  }
  return syncedCount;
};


